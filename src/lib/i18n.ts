export type TranslationKey = keyof typeof translations.en;

export function getStoredLanguage(): Language {
  if (typeof window === 'undefined') return 'en';
  try {
    const stored = localStorage.getItem(LANGUAGE_STORAGE_KEY) as Language | null;
    if (stored === 'en' || stored === 'rw') return stored;
  } catch {
    // fallback
  }
  return 'en';
}

export function setStoredLanguage(lang: Language): void {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, lang);
    window.dispatchEvent(new CustomEvent('rc6_language_change', { detail: lang }));
  } catch {
    // ignore
  }
}

export function translate(key: TranslationKey, lang: Language = 'en'): string {
  const dict = translations[lang] || translations.en;
  return (dict as any)[key] || translations.en[key] || key;
}
